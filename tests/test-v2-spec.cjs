#!/usr/bin/env node
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const spec = fs.readFileSync(path.join(root, 'SPEC-v2.0.md'), 'utf8');
const readme = fs.readFileSync(path.join(root, 'README.md'), 'utf8');
const changelog = fs.readFileSync(path.join(root, 'CHANGELOG.md'), 'utf8');
const migration = fs.readFileSync(path.join(root, 'MIGRATION-v2.0.md'), 'utf8');
const adaptation = fs.readFileSync(path.join(root, 'PROJECT-ADAPTATION-v2.0.md'), 'utf8');
const taskResolver = fs.readFileSync(path.join(root, 'template/scripts/task-context-resolver.cjs'), 'utf8');
const profile = fs.readFileSync(path.join(root, 'template/project-profile.toml'), 'utf8');
const capabilities = JSON.parse(fs.readFileSync(path.join(root, 'template/policy/capabilities.json'), 'utf8'));
const pillars = ['规范体系与目录架构','Agent 多客户端兼容','记忆与上下文管理','任务、看板与路线图管理','工程治理与初始化机制','自动化验证与质量门禁','长期演进与版本管理'];
for (const pillar of pillars) assert.ok(spec.includes(pillar), `missing pillar: ${pillar}`);
assert.match(spec, /2\.0 发布门槛/);
assert.match(spec, /明确不做/);
assert.match(spec, /不以真实 SaaS 项目作为 2\.0 验收前提/);
assert.match(readme, /SPEC-v2\.0\.md/);
assert.match(readme, /MIGRATION-v2\.0\.md/);
assert.match(changelog, /2\.0\.0-rc\.1/);
assert.match(migration, /--dry-run/);
assert.match(spec, /横向机制：母模板与项目适配/);
assert.match(adaptation, /core/);
assert.match(adaptation, /needs_review/);
assert.match(adaptation, /Task Context Resolver/);
assert.doesNotMatch(adaptation, /\\n/, 'adaptation document must not contain escaped newline literals');
assert.match(taskResolver, /resolveTaskContext/);
assert.match(taskResolver, /never edits project files/i);
assert.ok(profile.includes('status = "needs_review"'));
assert.ok(profile.includes('multi_agent = "off"'));
assert.equal(capabilities.schema_version, 1);
assert.equal(capabilities.core.always_enabled, true);
assert.ok(capabilities.capabilities.roadmap.requires);
console.log('test-v2-spec: all cases passed');
